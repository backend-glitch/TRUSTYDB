import oracledb from 'oracledb';

const tables = {
  SOURCES: `CREATE TABLE sources (
    source_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name VARCHAR2(100) NOT NULL UNIQUE
  )`,
  ENTITIES: `CREATE TABLE entities (
    entity_id NUMBER PRIMARY KEY,
    product_name VARCHAR2(500) NOT NULL,
    category VARCHAR2(200)
  )`,
  RECORDS: `CREATE TABLE records (
    record_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id NUMBER NOT NULL REFERENCES sources(source_id),
    entity_id NUMBER NOT NULL REFERENCES entities(entity_id),
    product_title VARCHAR2(500),
    price NUMBER(10,2) NOT NULL,
    stock NUMBER,
    record_timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
  )`,
  CONFLICTS: `CREATE TABLE conflicts (
    conflict_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_id NUMBER NOT NULL REFERENCES entities(entity_id),
    attribute_name VARCHAR2(50) NOT NULL,
    status VARCHAR2(30) NOT NULL
  )`,
  TRUST_SCORES: `CREATE TABLE trust_scores (
    trust_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id NUMBER NOT NULL REFERENCES records(record_id),
    trust_score NUMBER(5,2) NOT NULL,
    reason VARCHAR2(500)
  )`,
  RECOMMENDATIONS: `CREATE TABLE recommendations (
    recommendation_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conflict_id NUMBER NOT NULL REFERENCES conflicts(conflict_id),
    record_id NUMBER NOT NULL REFERENCES records(record_id),
    reason VARCHAR2(500)
  )`,
  SOURCE_HISTORY: `CREATE TABLE source_history (
    history_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id NUMBER NOT NULL REFERENCES sources(source_id),
    total_records NUMBER DEFAULT 0 NOT NULL,
    verified_records NUMBER DEFAULT 0 NOT NULL,
    correct_records NUMBER DEFAULT 0 NOT NULL,
    reliability_score NUMBER(5,2),
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
  )`
};

const indexes = [
  'CREATE INDEX trustydb_records_entity_ix ON records(entity_id)',
  'CREATE INDEX trustydb_conflicts_entity_ix ON conflicts(entity_id)',
  'CREATE INDEX trustydb_scores_record_ix ON trust_scores(record_id)',
  'CREATE INDEX trustydb_recommendations_conflict_ix ON recommendations(conflict_id)'
];

export async function ensureTrustySchema(connection) {
  const names = Object.keys(tables);
  const result = await connection.execute(
    `SELECT table_name AS "tableName" FROM user_tables WHERE table_name IN (${names.map((_, index) => `:table${index}`).join(', ')})`,
    Object.fromEntries(names.map((name, index) => [`table${index}`, name])),
    { outFormat: oracledb.OUT_FORMAT_OBJECT }
  );
  const existing = new Set(result.rows.map((row) => row.tableName));
  const created = [];
  for (const [name, statement] of Object.entries(tables)) {
    if (existing.has(name)) continue;
    await connection.execute(statement);
    created.push(name);
  }
  // Do not alter a user's existing schema merely to add indexes. Indexes are
  // created only when this bootstrap created at least one TRUSTYDB table.
  if (created.length) {
    for (const statement of indexes) {
      try { await connection.execute(statement); }
      catch (error) { if (error.errorNum !== 955) throw error; }
    }
  }
  return created;
}
